import { createClientFromRequest } from 'npm:@base44/sdk@0.7.0';
import { Keypair } from 'npm:@solana/web3.js@1.78.5';

Deno.serve(async (req) => {
    try {
        const base44 = createClientFromRequest(req);
        const user = await base44.auth.me();

        if (!user || user.user_type !== 'admin') {
            return Response.json({ success: false, error: 'Unauthorized: Admin access required.' }, { status: 401 });
        }

        // 1. Check if a vault already exists
        const existingConfigs = await base44.asServiceRole.entities.SystemConfig.filter({ config_key: 'vin_vault' });
        if (existingConfigs.length > 0) {
            return Response.json({ success: false, error: 'A VIN vault wallet already exists.' }, { status: 400 });
        }

        // 2. Generate a new Solana Keypair
        const keypair = Keypair.generate();
        const publicKey = keypair.publicKey.toBase58();
        const secretKeyArray = Array.from(keypair.secretKey);

        // 3. Save the new keypair to the SystemConfig entity
        await base44.asServiceRole.entities.SystemConfig.create({
            config_key: "vin_vault",
            public_key: publicKey,
            secret_key: secretKeyArray,
            description: "Primary VINmint token distribution vault, generated by admin."
        });

        return Response.json({
            success: true,
            message: "VIN Vault wallet generated and saved successfully.",
            publicKey: publicKey
        });

    } catch (error) {
        console.error('Error generating vault wallet:', error);
        return Response.json({ 
            success: false, 
            error: 'Failed to generate vault wallet', 
            details: error.message 
        }, { status: 500 });
    }
});